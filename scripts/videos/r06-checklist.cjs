const {open}=require('./lib.cjs');const {cut}=require('./cut.cjs');
(async()=>{const r=await open({url:'/demo?tab=housekeeping'});const p=r.page;
await r.start(); await r.wait(1200);
await r.moveTo(p.getByText('Tu checklist de limpieza').first());await r.wait(700);
await r.click(p.getByRole('button',{name:'Editar'}).first(),{after:1200});
await r.moveTo(p.getByText('En todas las limpiezas').first());await r.wait(1500);
r.mark('b');
await r.type(p.getByPlaceholder(/Nueva tarea/),'Revisar el control del aire',{delay:60});
await r.click(p.getByRole('button',{name:'Agregar'}).first(),{after:900});
await r.click(p.getByRole('button',{name:'Subir'}).last(),{after:700});
await r.click(p.getByRole('button',{name:'Subir'}).last(),{after:900});
r.mark('c');
const sel=p.locator('select').filter({hasText:'Cabaña Lapacho'}).first();
await r.moveTo(sel);await sel.selectOption({label:'Cabaña Palo Rosa'});await r.wait(500);
await r.type(p.getByPlaceholder(/Regar las plantas/),'Llenar el hidromasaje y probarlo',{delay:55});
await r.click(p.getByRole('button',{name:'Agregar'}).nth(1),{after:800});
await r.click(p.getByRole('button',{name:'Guardar'}).first(),{after:1500});
const m=await r.stop('videos-out/r06.app.mp4');console.log(m);
console.log(cut('videos-out/r06.app.mp4',[0,m.b,m.c],'videos-out/Loomi_checklist-limpieza'));})();
